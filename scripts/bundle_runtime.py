"""Package the actual Python grader into a browser-loadable source bundle.

Use --check in CI to ensure the committed bundle matches the Python sources.
The source, rather than a second grading implementation, runs under Pyodide.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "_extensions/stack-sympy/runtime-sources.js"


def generate() -> str:
    sources = {
        f"stack_sympy/{path.name}": path.read_text(encoding="utf-8")
        for path in sorted((ROOT / "_extensions/stack-sympy/stack_sympy").glob("*.py"))
        if path.name not in {"cli.py"}
    }
    if "stack_sympy/engine.py" not in sources:
        raise RuntimeError("stack_sympy/engine.py is required")
    return ("// Generated by scripts/bundle_runtime.py; do not edit.\n"
            "globalThis.STACK_SYMPY_SOURCES = "
            + json.dumps(sources, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
            + ";\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.error("runtime-sources.js is stale; run python scripts/bundle_runtime.py")
        vendor = ROOT / "_extensions/stack-sympy/vendor"
        expected = json.loads((vendor / "provenance.json").read_text(encoding="utf-8"))["sha256"]
        actual = hashlib.sha256((vendor / "pyodide-runtime.js").read_bytes()).hexdigest()
        if actual != expected:
            parser.error("vendored Pyodide bootstrap differs from its pinned provenance")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(OUTPUT)


if __name__ == "__main__":
    main()
